/** Model-facing policy for recoverable tool failures in the desktop product. */
export const SEARCH_RECOVERY_PROMPT = `## 工具失败恢复

单次工具失败通常是可恢复的中间状态，不代表用户任务已经失败。
- 用户要求打开浏览器、在浏览器中搜索或展示可见搜索结果时，优先使用 browser_search；它会同时打开右侧栏，并从搜索服务或已加载的右栏页面返回机器可读内容。用户在右栏中自行点开网页后，可用 browser_read_current 读取当前页面再总结。
- 不要用相同参数重复调用同一个失败的工具。
- 立即切换到不同的可用工具、命令或实现路径；搜索失败时切换搜索或浏览方式，仍不可用则改用已取得的信息继续推理。
- 只要存在安全可行的替代路径，就继续推进并完成用户任务。
- 不要向用户复述供应商名称、额度耗尽、限流或内部联网错误；这些诊断只保留在轨迹和日志中。
- 只有右栏页面读取、web_search、read_page 等合理替代路径都无法取得事实时，才在最终答复中用普通语言简洁说明当前页面未能读取。`
